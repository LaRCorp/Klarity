def main():
    if not os.path.exists(POT_PATH):
        print(f"Error: {POT_PATH} does not exist", file=sys.stderr)
        sys.exit(1)

    pot = polib.pofile(POT_PATH)
    po = polib.POFile()

    # Set metadata
    po.metadata = {
        'Project-Id-Version': 'klarity 1.1',
        'Report-Msgid-Bugs-To': 'dev@larcorp.org',
        'POT-Creation-Date': pot.metadata.get('POT-Creation-Date', '2026-11-24 21:00+0700'),
        'PO-Revision-Date': '2026-11-24 21:35+0700',
        'Last-Translator': 'LaRCorp Localization Team <dev@larcorp.org>',
        'Language-Team': 'Russian <ru@li.org>',
        'Language': 'ru',
        'MIME-Version': '1.0',
        'Content-Type': 'text/plain; charset=UTF-8',
        'Content-Transfer-Encoding': '8bit',
        'Plural-Forms': 'nplurals=3; plural=(n%10==1 && n%100!=11 ? 0 : n%10>=2 && n%10<=4 && (n%100<10 || n%100>=20) ? 1 : 2);',
        'X-Generator': 'Klarity Localization Tool 1.1'
    }

    missing_translations = []

    for entry in pot:
        msgid = entry.msgid
        if not msgid:
            continue

        ru_translation = TRANSLATIONS.get(msgid)
        if ru_translation is None:
            # Check trimmed or normalized
            ru_translation = TRANSLATIONS.get(msgid.strip())

        if ru_translation is None:
            missing_translations.append(msgid)
            ru_translation = msgid # fallback

        po_entry = polib.POEntry(
            msgid=msgid,
            msgstr=ru_translation,
            occurrences=entry.occurrences,
            flags=entry.flags,
            comment=entry.comment
        )
        po.append(po_entry)

    os.makedirs(os.path.dirname(PO_PATH), exist_ok=True)
    po.save(PO_PATH)
    print(f"Saved {len(po)} entries to {PO_PATH}")

    if missing_translations:
        print(f"WARNING: {len(missing_translations)} strings missing in TRANSLATIONS dictionary:")
        for m in missing_translations[:30]:
            print("  MISSING:", repr(m))
        sys.exit(2)
    else:
        print("SUCCESS: 100% of strings have Russian translations!")

if __name__ == "__main__":
    main()
