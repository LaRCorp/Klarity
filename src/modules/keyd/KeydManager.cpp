KeydManager::KeydManager(QObject *parent)
    : QObject(parent)
{
    load();
    checkServiceStatus();
}

QVariantList KeydManager::mappings() const
{
    QVariantList list;
    list.reserve(m_items.size());
    for (const auto &item : m_items) {
        list.append(item.toMap());
    }
    return list;
}

QStringList KeydManager::layers() const
{
    QSet<QString> set;
    for (const auto &item : m_items) {
        set.insert(item.layer);
    }
    QStringList list = set.values();
    list.sort();
    if (!list.contains(QStringLiteral("main"))) {
        list.prepend(QStringLiteral("main"));
    }
    return list;
}

QString KeydManager::computeFriendlyDescription(const QString &key, const QString &action) const
{
    const QString trimmedAct = action.trimmed();
    if (trimmedAct.startsWith(QStringLiteral("overload("))) {
        return i18n("Overload: Dual-role key (modifier on hold, key on tap)");
    }
    if (trimmedAct.startsWith(QStringLiteral("macro("))) {
        return i18n("Macro: Sequence of keys or actions");
    }
    if (trimmedAct.startsWith(QStringLiteral("layer("))) {
        return i18n("Layer Switch: Activates secondary key layer");
    }
    if (trimmedAct.startsWith(QStringLiteral("swap("))) {
        return i18n("Swap: Swaps key functionality with modifier");
    }
    if (key == trimmedAct) {
        return i18n("Identity remap / Passthrough protection");
    }

    return i18n("Remapped to %1", trimmedAct);
}

void KeydManager::load()
{
    m_isLoading = true;
    emit isLoadingChanged();
    m_items.clear();
    m_deviceIds.clear();

    const QString path = configPath();
    QFile file(path);

    if (file.open(QIODevice::ReadOnly | QIODevice::Text)) {
        QTextStream in(&file);
        QString currentSection;
        int index = 0;

        while (!in.atEnd()) {
            const QString rawLine = in.readLine().trimmed();
            if (rawLine.isEmpty() || rawLine.startsWith(QLatin1Char('#'))) {
                continue;
            }

            if (rawLine.startsWith(QLatin1Char('[')) && rawLine.endsWith(QLatin1Char(']'))) {
                currentSection = rawLine.mid(1, rawLine.length() - 2).trimmed();
                continue;
            }

            if (currentSection == QStringLiteral("ids")) {
                m_deviceIds.append(rawLine);
                continue;
            }

            const int eqIdx = rawLine.indexOf(QLatin1Char('='));
            if (eqIdx != -1) {
                const QString k = rawLine.left(eqIdx).trimmed();
                const QString a = rawLine.mid(eqIdx + 1).trimmed();

                KeydMapping mapping;
                mapping.id = QStringLiteral("keyd_%1").arg(index++);
                mapping.layer = currentSection.isEmpty() ? QStringLiteral("main") : currentSection;
                mapping.key = k;
                mapping.action = a;
                mapping.isMacro = a.startsWith(QStringLiteral("macro("), Qt::CaseInsensitive);
                mapping.description = computeFriendlyDescription(k, a);

                m_items.append(mapping);
            }
        }
        file.close();
    } else {
        LogModel::instance()->append(
            QStringLiteral("Keyd"),
            QStringLiteral("warn"),
            QStringLiteral("Could not read %1 directly. Ready to configure.").arg(path)
        );
    }

    m_isLoading = false;
    emit isLoadingChanged();
    emit mappingsChanged();
}

QString KeydManager::generateConfigContent() const
{
    QString content;
    QTextStream out(&content);

    out << "# Generated by Klarity - Linux Control Center\n";
    out << "# Configuration for keyd (/etc/keyd/default.conf)\n\n";

    if (!m_deviceIds.isEmpty()) {
        out << "[ids]\n";
        for (const auto &id : m_deviceIds) {
            out << id << "\n";
        }
        out << "\n";
    }

    // Group mappings by layer
    QMap<QString, QVector<KeydMapping>> layerMap;
    for (const auto &item : m_items) {
        layerMap[item.layer].append(item);
    }

    // Always output [main] first if present
    if (layerMap.contains(QStringLiteral("main"))) {
        out << "[main]\n";
        for (const auto &m : layerMap.value(QStringLiteral("main"))) {
            out << m.key << " = " << m.action << "\n";
        }
        out << "\n";
        layerMap.remove(QStringLiteral("main"));
    }

    for (auto it = layerMap.begin(); it != layerMap.end(); ++it) {
        out << "[" << it.key() << "]\n";
        for (const auto &m : it.value()) {
            out << m.key << " = " << m.action << "\n";
        }
        out << "\n";
    }

    return content;
}

bool KeydManager::addMapping(const QString &layer, const QString &key, const QString &action, const QString &description)
{
    if (key.trimmed().isEmpty() || action.trimmed().isEmpty()) {
        emit operationFinished(false, QStringLiteral("Key and action cannot be empty."));
        return false;
    }

    KeydMapping item;
    item.id = QStringLiteral("keyd_%1").arg(QDateTime::currentMSecsSinceEpoch());
    item.layer = layer.trimmed().isEmpty() ? QStringLiteral("main") : layer.trimmed();
    item.key = key.trimmed();
    item.action = action.trimmed();
    item.isMacro = item.action.startsWith(QStringLiteral("macro("), Qt::CaseInsensitive);
    item.description = description.trimmed().isEmpty() ? computeFriendlyDescription(item.key, item.action) : description.trimmed();

    m_items.append(item);
    emit mappingsChanged();

    saveAndReload();
    return true;
}

bool KeydManager::editMapping(const QString &id, const QString &layer, const QString &key, const QString &action, const QString &description)
{
    for (int i = 0; i < m_items.size(); ++i) {
        if (m_items[i].id == id) {
            m_items[i].layer = layer.trimmed().isEmpty() ? QStringLiteral("main") : layer.trimmed();
            m_items[i].key = key.trimmed();
            m_items[i].action = action.trimmed();
            m_items[i].isMacro = m_items[i].action.startsWith(QStringLiteral("macro("), Qt::CaseInsensitive);
            m_items[i].description = description.trimmed().isEmpty() ? computeFriendlyDescription(m_items[i].key, m_items[i].action) : description.trimmed();

            emit mappingsChanged();
            saveAndReload();
            return true;
        }
    }

    emit operationFinished(false, QStringLiteral("Mapping not found."));
    return false;
}

bool KeydManager::deleteMapping(const QString &id)
{
    for (int i = 0; i < m_items.size(); ++i) {
        if (m_items[i].id == id) {
            m_items.removeAt(i);
            emit mappingsChanged();
            saveAndReload();
            return true;
        }
    }

    emit operationFinished(false, QStringLiteral("Mapping not found."));
    return false;
}

void KeydManager::saveAndReload()
{
    const QString content = generateConfigContent();
    const QString tempPath = QDir::tempPath() + QStringLiteral("/klarity_keyd_default.conf");

    QFile tempFile(tempPath);
    if (!tempFile.open(QIODevice::WriteOnly | QIODevice::Text | QIODevice::Truncate)) {
        emit operationFinished(false, QStringLiteral("Failed to prepare temporary configuration file."));
        return;
    }

    QTextStream out(&tempFile);
    out << content;
    tempFile.close();

    LogModel::instance()->append(
        QStringLiteral("Keyd"),
        QStringLiteral("info"),
        QStringLiteral("Writing configuration to /etc/keyd/default.conf with elevated privileges...")
    );

    auto runner = new PkexecRunner(this);
    connect(runner, &PkexecRunner::finished, this, [this, tempPath](int exitCode, const QString &output) {
        QFile::remove(tempPath);
        checkServiceStatus();

        if (exitCode == 0) {
            LogModel::instance()->append(QStringLiteral("Keyd"), QStringLiteral("info"), QStringLiteral("Keyd configuration applied and daemon reloaded"));
            emit operationFinished(true, QStringLiteral("Keyd configuration saved and service reloaded successfully."));
        } else if (exitCode == 126 || exitCode == 127) {
            LogModel::instance()->append(QStringLiteral("Keyd"), QStringLiteral("warn"), QStringLiteral("Keyd operation cancelled by user"));
            emit operationFinished(false, QStringLiteral("Operation cancelled by user."));
        } else {
            LogModel::instance()->append(QStringLiteral("Keyd"), QStringLiteral("error"), QStringLiteral("Failed to reload keyd (code %1): %2").arg(exitCode).arg(output));
            emit operationFinished(false, QStringLiteral("Failed to apply keyd configuration: %1").arg(output));
        }
    });

    const QString shellScript = QStringLiteral("cp %1 /etc/keyd/default.conf && chmod 644 /etc/keyd/default.conf && keyd reload").arg(tempPath);
    runner->runRoot(QStringLiteral("sh"), {QStringLiteral("-c"), shellScript});
}

void KeydManager::checkServiceStatus()
{
    QProcess proc;
    proc.start(QStringLiteral("systemctl"), {QStringLiteral("is-active"), QStringLiteral("keyd")});
    proc.waitForFinished(1000);

    const QString out = QString::fromUtf8(proc.readAllStandardOutput()).trimmed();
    const bool active = (out == QStringLiteral("active"));
    if (m_isServiceActive != active) {
        m_isServiceActive = active;
        emit serviceStatusChanged();
    }
}

